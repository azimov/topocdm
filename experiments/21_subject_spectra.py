"""
21 -- per-subject spectra: MIMIC patients vs topocdm synthetic patients.

A subject spectrum is the normalised Laplacian spectrum of one patient's
concept co-occurrence graph: nodes are the concepts the patient has, an edge
means two concepts were recorded on the same day, and the eigenvalue sequence
is the patient's fingerprint. It is a per-patient object, so it can show a
difference that the cohort-level spectrum averages away.

The graph is restricted to condition and drug concepts. The all-concept graph
is near-complete — one visit can carry hundreds of measurements — so its
Laplacian spectrum is degenerate (almost all eigenvalues equal 1) and cannot
discriminate. The condition-drug graph is sparse enough to have structure.

The comparison is: MIMIC patients against patients generated by topocdm fitted
to MIMIC (the visit-anchored model). If the model reproduces the encounter
structure, the two families of lines should look alike; if it only reproduces
when things happen and not what happens together, they will not.

Run: MPLCONFIGDIR=./.mplconfig .venv/bin/python experiments/21_subject_spectra.py
"""

